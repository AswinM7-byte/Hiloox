const assert = require('node:assert/strict');
const fs = require('node:fs');
const vm = require('node:vm');
const source = fs.readFileSync('src/lib/useViewportReveal.js','utf8');
const body = source.slice(source.indexOf('    const element ='),source.indexOf('\n  }, [selector'));
const classes = new Set();
const node = { classList:{add:x=>classes.add(x),remove:x=>classes.delete(x)},closest:()=>false };
let callback, disconnected=0, unobserved=0, observed=0, preferenceCallback;
const preference={matches:false,addEventListener:(_,cb)=>preferenceCallback=cb,removeEventListener:()=>preferenceCallback=null};
const context={root:{current:{querySelectorAll:()=>[node]}},selector:'[data-contact-reveal]',exclude:'',className:'contact-enter',window:{matchMedia:()=>preference},IntersectionObserver:class {constructor(cb){callback=cb;}observe(){observed++;}unobserve(){unobserved++;}disconnect(){disconnected++;}}};
context.window.IntersectionObserver=context.IntersectionObserver;
const cleanup=vm.runInNewContext(`(()=>{${body}})()`,context);
assert.equal(classes.size,0,'baseline content has no hiding class');
callback([{target:node,isIntersecting:false}]); assert.equal(classes.size,0);
callback([{target:node,isIntersecting:true}]); assert.ok(classes.has('contact-enter')); assert.equal(unobserved,1,'entrance unobserves to avoid replay');
preference.matches=true; preferenceCallback(); assert.equal(classes.size,0,'reduced motion removes animation');
assert.equal(observed,1,'reduced motion does not observe');
cleanup(); assert.equal(preferenceCallback,null); assert.ok(disconnected>=2);
console.log('PASS: progressive reveal baseline, viewport entry, one-shot observation, reduced-motion reset, cleanup.');
